/* ---------- Language engine ---------- */
const norm = (s) => s.replace(/\s+/g, " ").trim();
const AR_N = Object.fromEntries(Object.entries(AR).map(([k, v]) => [norm(k), v]));

function getLang() {
  const url = new URLSearchParams(location.search).get("lang");
  if (url === "ar" || url === "en") return url;
  try { return localStorage.getItem("sidra-lang") || "en"; } catch (e) { return "en"; }
}
const LANG = getLang();
const isAR = LANG === "ar";

/* t("English {x}", {x: 1}) -> translated text with values filled in */
function t(en, vars = {}) {
  let s = isAR ? (AR_N[norm(en)] ?? en) : en;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

function applyTranslations(root = document) {
  if (!isAR) return;
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    const tr = AR_N[norm(el.innerHTML)];
    if (tr) el.innerHTML = tr;
  });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.placeholder);
  });
}

function setLang(lang) {
  try { localStorage.setItem("sidra-lang", lang); } catch (e) { /* storage blocked: the URL keeps the choice */ }
  const url = new URL(location.href);
  url.searchParams.set("lang", lang);
  location.href = url.toString();
}

document.documentElement.lang = LANG;
document.documentElement.dir = isAR ? "rtl" : "ltr";
document.title = isAR ? document.title.replace("Sidra Dashboard", "لوحة بيانات سدرة").replace("The Sidra Idea", "فكرة سدرة") : document.title;

document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
  const btn = document.getElementById("lang-btn");
  if (btn) {
    btn.textContent = isAR ? "English" : "العربية";
    btn.addEventListener("click", () => setLang(isAR ? "en" : "ar"));
  }
  // keep the language when moving between pages
  if (isAR) document.querySelectorAll('a[href$=".html"], a[href*=".html#"]').forEach((a) => {
    const [path, hash] = a.getAttribute("href").split("#");
    a.setAttribute("href", `${path}?lang=ar${hash ? `#${hash}` : ""}`);
  });
});
